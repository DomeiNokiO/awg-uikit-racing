  const __noop = () => ({ classList: { add(){}, remove(){} }, style: {}, dataset: {}, setAttribute(){}, appendChild(){}, addEventListener(){}, removeEventListener(){}, focus(){}, blur(){}, querySelector(){ return null; }, querySelectorAll(){ return []; }, closest(){ return null; }, getBoundingClientRect(){ return { left:0, top:0, right:0, bottom:0, width:0, height:0 }; }, contains(){ return false; } });
