`;

const moduleBodies = [shim].concat(modules.map((m) => ensureEol(stripBanners(read(m)))));

const tailExports = `
const _Awg = (typeof globalThis !== 'undefined' && globalThis.Awg) || (typeof window !== 'undefined' && window.Awg) || null;
